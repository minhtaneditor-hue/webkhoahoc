// Turns docs/cham-video/tieu-chi-cham.md into the rubric the scoring API sends to Claude.
// Run after editing the md:  node scripts/build-cham-rubric.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const md = readFileSync('docs/cham-video/tieu-chi-cham.md', 'utf8');
const start = md.indexOf('## 0.');
const end = md.indexOf('## 6.');
if (start < 0 || end < 0) throw new Error('Không thấy mục 0 hoặc mục 6 trong file tiêu chí');

const text = md.slice(start, end)
  .split('\n')
  .filter((l) => !l.includes('[TẤN SỬA]'))            // notes to Tấn, not rules
  .map((l) => l
    .replace(/\s*\[(?:B\d|TH|AU|BLOG|SANG|STORY|HOOK|CONCEPT|GOC|TAN-WS|CANH|VIDEO)[^\]]*\]/g, '') // source tags
    .replace(/\s*\*\*\(suy ra\)\*\*|\s*\(suy ra\)/g, ''))
  .join('\n')
  .replace(/\n{3,}/g, '\n\n')
  .trim();

writeFileSync('src/lib/cham-video/rubric.ts',
  `// Generated by scripts/build-cham-rubric.mjs from docs/cham-video/tieu-chi-cham.md. Edit the md, then rerun.\nexport const RUBRIC = ${JSON.stringify(text)};\n`);
console.log('rubric chars:', text.length);
